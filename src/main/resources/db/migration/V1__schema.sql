CREATE TABLE temas (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome varchar(80) NOT NULL,
 chave varchar(160) NOT NULL UNIQUE
);
CREATE TABLE usuarios (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 email varchar(150) NOT NULL UNIQUE,
 nome varchar(100) NOT NULL,
 senha_hash varchar(100) NOT NULL,
 papel varchar(16) NOT NULL
);
CREATE TABLE consultas (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 titulo varchar(140) NOT NULL,
 descricao varchar(1500) NOT NULL,
 bairro varchar(80) NOT NULL,
 tema_id bigint NOT NULL REFERENCES temas(id),
 estado varchar(16) NOT NULL,
 criada_em timestamp(6) with time zone NOT NULL
);
CREATE INDEX ix_consultas_tema ON consultas(tema_id);
CREATE TABLE votos (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 consulta_id bigint NOT NULL REFERENCES consultas(id),
 usuario_id bigint NOT NULL REFERENCES usuarios(id),
 escolha varchar(16) NOT NULL,
 registrado_em timestamp(6) with time zone NOT NULL,
 CONSTRAINT uk_voto_consulta_usuario UNIQUE (consulta_id,usuario_id)
);
